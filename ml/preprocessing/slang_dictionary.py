# Compile case-insensitive regex pattern for whole words
_regex_pattern = re.compile(
    r"\b(" + "|".join(re.escape(k) for k in sorted(SLANG_DICTIONARY.keys(), key=len, reverse=True)) + r")\b",
    re.IGNORECASE
)

def expand_internet_slang(text: str) -> str:
    """
    Expands English slang, short forms, Gen Z / Gen Alpha words, and internet abbreviations
    while preserving original casing and word boundary structure.
    """
    if not isinstance(text, str) or not text.strip():
        return text

    def _replace_match(match: re.Match) -> str:
        word = match.group(0)
        lowered = word.lower()
        replacement = SLANG_DICTIONARY.get(lowered, word)
        
        # Match capitalized word if original was capitalized
        if word.isupper() and len(word) > 1:
            return replacement.upper()
        elif word[0].isupper() and not word.islower():
            return replacement.capitalize()
        return replacement

    return _regex_pattern.sub(_replace_match, text)
